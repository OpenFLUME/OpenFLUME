"""Build hook: refuse to produce a wheel/sdist without the bundled JS core.

The Node bridge and coolprop.wasm in src/openflume/_js/ are generated by
`npm run build:python` at the repository root. Building from an sdist works
without Node because the sdist already carries them.
"""

from __future__ import annotations

from pathlib import Path

from hatchling.builders.hooks.plugin.interface import BuildHookInterface

REQUIRED = ("openflume-bridge.mjs", "coolprop.wasm")


class CustomBuildHook(BuildHookInterface):
    def initialize(self, version: str, build_data: dict) -> None:
        root = Path(self.root)
        js_dir = root / "src" / "openflume" / "_js"
        missing = [name for name in REQUIRED if not (js_dir / name).is_file()]
        if not (root / "LICENSE").is_file():
            missing.append("../LICENSE copy")
        if missing:
            raise RuntimeError(
                "openflume: bundled JS core not found ("
                + ", ".join(missing)
                + "). Run `npm ci && npm run build:python` at the repository "
                "root before building the Python package."
            )
